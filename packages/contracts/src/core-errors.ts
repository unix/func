export enum ErrorScope {
  RUNTIME = 'F_RUNTIME',
  SYSTEM = 'F_SYSTEM',
}

export type ErrorCode<
  Scope extends ErrorScope = ErrorScope,
  Code extends string = string,
> = `${Scope}_${Code}`

export const formatErrorCode = <Scope extends ErrorScope, Code extends string>(
  scope: Scope,
  code: Code,
): ErrorCode<Scope, Code> => `${scope}_${code}`

